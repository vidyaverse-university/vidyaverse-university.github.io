/* VidyaVerse v2.3 — Programmes (#/programmes, #/programmes/<id>): degrees, classes and certificates laid out
   term by term (semester / year / subject columns) using existing courses. Data: programmes/index.json
   (generated by tmp/vv2/build_programmes.py). Progress comes from the local store only. */
(function () {
  'use strict';
  var VV2 = window.VV2, h = VV2.h, store = VV2.store, D = VV2.data;
  var PG = VV2.Programmes = {};
  var LEVELS = [
    ['school', '🏫', 'School', 'Class 1\u201312 \u00b7 every subject'],
    ['UG', '🎓', 'Undergraduate degrees', 'B.Tech, B.Sc, B.Com, BA, LLB, MBBS, BDS\u2026'],
    ['PG', '🔬', 'Postgraduate & research', 'MBA and specialisations, M.Sc, M.Tech, PhD'],
    ['professional', '💼', 'Professional certificates', 'Cloud, IT infrastructure, data, AI, software'],
    ['certificate', '🛠\uFE0F', 'Vocational certificates', 'Repair, electrician, plumbing and other trades']
  ].map(function (l) { return { id: l[0], icon: l[1], name: l[2], desc: l[3] }; });
  function lvl(id) { return LEVELS.filter(function (l) { return l.id === id; })[0] || { id: id, icon: '📘', name: id, desc: '' }; }

  /* course info: catalogue first, then the build's fallback for packs not yet in the catalogue */
  function info(id) {
    var c = D.byId[id]; if (c) return c;
    var x = (D.progCat || {})[id]; return x ? { id: id, title: x[0], minutes: +x[1] || 0, lessons: +x[2] || 0, pending: true } : null;
  }
  function resolve(p) {
    if (p._res) return p._res;
    var seen = {};
    p._res = (p.terms || []).map(function (t) {
      var cs = [];
      (t.courses || []).forEach(function (id) { var c = info(id); if (c && !seen[id]) { seen[id] = 1; cs.push(c); } else if (!c) console.warn('[programmes] ' + p.id + ': unknown course "' + id + '" (skipped)'); });
      return { title: t.title, courses: cs };
    }).filter(function (t) { return t.courses.length; });
    return p._res;
  }
  function all(p) { var a = []; resolve(p).forEach(function (t) { a = a.concat(t.courses); }); return a; }
  function minutes(list) { return list.reduce(function (s, c) { return s + (+c.minutes || 0); }, 0); }
  function progress(p) {
    var tot = 0, done = 0, next = null;
    all(p).forEach(function (c) {
      var n = +c.lessons || 0; tot += n; var d = store.courseDone(c.id, n); done += d;
      if (!next && d < n) { for (var i = 1; i <= n; i++) { if (!store.isDone(c.id + '.l' + i)) { next = c.id + '.l' + i; break; } } }
    });
    return { tot: tot, done: done, pct: tot ? Math.round(done / tot * 100) : 0, next: next };
  }
  PG.progress = progress; PG.all = all;

  PG.render = function (main, id, q) {
    VV2.loading(main, 'Opening the programme office\u2026');
    return Promise.all([D.index().catch(function () { }), D.programmes()]).then(function (r) {
      var list = r[1] || [];
      if (id) { var p = list.filter(function (x) { return x.id === id; })[0]; if (p) return detail(main, p, list); }
      return gallery(main, list, id, q || {});
    }).catch(function (e) { VV2.errorView(main, 'Programmes are not available', 'We could not load the programme list' + (e && e.message ? ' (' + e.message + ')' : '') + '.', function () { VV2.render(); }); });
  };

  /* ---------------- gallery ---------------- */
  function gallery(main, list, missing, q) {
    VV2.setTitle('Programmes'); main.innerHTML = '';
    var w = h('div', { class: 'wrap pg' }); main.appendChild(w);
    var totMin = 0, totC = {}; list.forEach(function (p) { all(p).forEach(function (c) { if (!totC[c.id]) { totC[c.id] = 1; totMin += +c.minutes || 0; } }); });
    w.appendChild(h('div', { class: 'hub-head' }, [h('div', null, [h('p', { class: 'eyebrow' }, 'Pathyakram \u00b7 Degrees, classes & certificates'), h('h1', null, '🎓 Programmes'),
      h('p', { class: 'lead' }, 'Pick a degree, a school class or a certificate and see every course laid out semester by semester. ' + list.length + ' programmes \u00b7 ' + VV2.approx(Object.keys(totC).length) + ' courses \u00b7 ' + VV2.hrsLong(totMin) + '.'),
      h('p', { class: 'muted small-note' }, 'Study companions built from VidyaVerse courses \u2014 not accredited degrees or official certifications.')])]));
    if (missing) w.appendChild(h('p', { class: 'w-fb no', role: 'status' }, 'We could not find the programme \u201c' + missing + '\u201d \u2014 here are all of them.'));
    var cur = LEVELS.some(function (l) { return l.id === q.l; }) ? q.l : '';
    var inp = h('input', { type: 'search', class: 'pg-q', placeholder: 'Find a programme \u2014 try \u201cCSE\u201d, \u201cClass 10\u201d, \u201cMBA\u201d, \u201cAWS\u201d, \u201celectrician\u201d', 'aria-label': 'Find a programme', autocomplete: 'off', value: q.q || '' });
    var chips = h('div', { class: 'seg pg-levels', role: 'group', 'aria-label': 'Filter by level' });
    var out = h('div', { class: 'pg-out', 'aria-live': 'polite' });
    w.appendChild(h('div', { class: 'pg-tools' }, [h('div', { class: 'searchbar' }, [h('span', { class: 'sb-i', 'aria-hidden': 'true' }, '🔍'), inp]), chips]));
    w.appendChild(out);
    [{ id: '', icon: '\u2728', name: 'All' }].concat(LEVELS).forEach(function (l) {
      var n = l.id ? list.filter(function (p) { return p.level === l.id; }).length : list.length; if (l.id && !n) return;
      chips.appendChild(h('button', { type: 'button', class: 'seg-b', 'data-l': l.id, 'aria-pressed': l.id === cur ? 'true' : 'false', onclick: function () { cur = l.id; VV2.$$('.seg-b', chips).forEach(function (b) { b.setAttribute('aria-pressed', b.getAttribute('data-l') === cur ? 'true' : 'false'); }); keep(); draw(); } }, (l.icon ? l.icon + ' ' : '') + (l.id ? l.name.split(' ')[0] : l.name) + ' (' + n + ')'));
    });
    function keep() { var qs = []; if (cur) qs.push('l=' + encodeURIComponent(cur)); if (inp.value.trim()) qs.push('q=' + encodeURIComponent(inp.value.trim())); try { history.replaceState(null, '', '#/programmes' + (qs.length ? '?' + qs.join('&') : '')); } catch (e) { } }
    /* exact word hits (score >= 10) first; typo-tolerant title match as a fallback */
    function match(p, v) {
      if (!v) return true;
      var t = VV2.fuzzy(v, p.title + ' ' + p.short);
      if (t >= 10 || VV2.fuzzy(v, (p.summary || '') + ' ' + (p.group || '') + ' ' + lvl(p.level).name) >= 10) return true;
      if (v.length > 2 && all(p).some(function (c) { return VV2.fuzzy(v, c.title) >= 10; })) return true;
      return t > 0 && !list.some(function (x) { return VV2.fuzzy(v, x.title + ' ' + x.short) >= 10; });
    }
    function draw() {
      out.innerHTML = '';
      var v = inp.value.trim(), shown = list.filter(function (p) { return (!cur || p.level === cur) && match(p, v); });
      if (!shown.length) { out.appendChild(h('div', { class: 'empty-state small' }, [h('div', { class: 'es-art', 'aria-hidden': 'true' }, '🧭'), h('p', null, 'No programme matches \u201c' + v + '\u201d. Try a shorter word, or search every course instead.'), h('a', { class: 'btn small', href: '#/search?q=' + encodeURIComponent(v) }, '🔍 Search all courses')])); return; }
      LEVELS.forEach(function (l) {
        var ps = shown.filter(function (p) { return p.level === l.id; }); if (!ps.length) return;
        var sec = h('section', { class: 'pg-sec', 'aria-labelledby': 'pgh-' + l.id }, [h('div', { class: 'section-h' }, [h('div', null, [h('p', { class: 'eyebrow' }, l.desc), h('h2', { id: 'pgh-' + l.id }, l.icon + ' ' + l.name + ' (' + ps.length + ')')])])]);
        var g = h('div', { class: 'pg-gal' }); sec.appendChild(g);
        ps.forEach(function (p, i) { g.appendChild(card(p, i)); });
        out.appendChild(sec);
      });
    }
    var t = 0; inp.addEventListener('input', function () { clearTimeout(t); t = setTimeout(function () { keep(); draw(); }, 120); });
    draw();
  }
  function card(p, i) {
    var cs = all(p), pr = progress(p), m = minutes(cs);
    return h('a', { class: 'card pg-card' + (cs.length ? '' : ' soon'), href: '#/programmes/' + encodeURIComponent(p.id), style: { '--c': p.color || 'var(--pri)', animationDelay: Math.min(i * 30, 300) + 'ms' }, 'data-say': p.title }, [
      h('div', { class: 'pg-card-h' }, [h('span', { class: 'pg-card-i', 'aria-hidden': 'true' }, p.icon || '🎓'), cs.length ? h('span', { html: VV2.ring(pr.pct, 46, p.color, pr.pct + '% of ' + p.short + ' done') }) : null]),
      h('b', null, p.short || p.title), h('small', { class: 'pg-card-t' }, p.title),
      h('div', { class: 'rm-pills' }, [h('span', { class: 'pill' }, '🗓 ' + p.duration), cs.length ? h('span', { class: 'pill' }, cs.length + ' courses') : h('span', { class: 'pill sens' }, '🚧 being written'), cs.length ? h('span', { class: 'pill', title: 'Estimated guided study time (lessons, labs and quizzes) \u2014 not video hours' }, VV2.hrs(m)) : null])
    ]);
  }

  /* ---------------- detail ---------------- */
  function detail(main, p, list) {
    VV2.setTitle(p.short + ' \u00b7 Programme'); main.innerHTML = '';
    var terms = resolve(p), cs = all(p), pr = progress(p), m = minutes(cs), color = p.color || 'var(--pri)', L = lvl(p.level);
    var lessons = cs.reduce(function (s, c) { return s + (+c.lessons || 0); }, 0);
    var w = h('div', { class: 'wrap pg pg-detail', style: { '--c': color } }); main.appendChild(w);
    w.appendChild(h('nav', { class: 'crumbs no-print', 'aria-label': 'Breadcrumb' }, [h('a', { href: '#/programmes' }, '🎓 Programmes'), h('span', { 'aria-hidden': 'true' }, ' / '), h('a', { href: '#/programmes?l=' + encodeURIComponent(p.level) }, L.name), h('span', { 'aria-hidden': 'true' }, ' / '), h('span', null, p.short)]));
    var startB = h('a', { class: 'btn primary big no-print', href: pr.next ? '#/lesson/' + encodeURIComponent(pr.next) : '#/programmes/' + encodeURIComponent(p.id) }, cs.length ? (pr.next ? (pr.done ? '\u25B6 Continue' : '\u25B6 Start the programme') : '🎉 All done \u2014 review') : '🚧 Being written');
    if (!pr.next) startB.addEventListener('click', function (e) { e.preventDefault(); if (cs.length) { VV2.confetti(); VV2.toast('Every course in ' + p.short + ' is done. Brilliant!', '🎓'); } });
    else { var nc = info(pr.next.replace(/\.l\d+$/, '')); if (nc) startB.setAttribute('title', 'Next: ' + nc.title); }
    w.appendChild(h('header', { class: 'rm-hero pg-hero' }, [
      h('div', null, [h('p', { class: 'eyebrow' }, (p.icon || '🎓') + ' ' + L.name + (p.group ? ' \u00b7 ' + p.group : '')), h('h1', null, p.title), p.summary ? h('p', { class: 'lead' }, p.summary) : null,
        h('div', { class: 'rm-pills' }, [h('span', { class: 'pill' }, '🗓 ' + p.duration), h('span', { class: 'pill' }, terms.length + ' ' + (terms[0] && /^Semester/.test(terms[0].title) ? 'semesters' : terms[0] && /^Year/.test(terms[0].title) ? 'years' : 'parts')), h('span', { class: 'pill' }, cs.length + ' courses \u00b7 ' + lessons + ' lessons'), h('span', { class: 'pill', title: 'Estimated guided study time \u2014 not video hours' }, VV2.hrsLong(m)), cs.length ? h('span', { class: 'pill' }, pr.done + ' / ' + pr.tot + ' lessons done') : null]),
        h('p', { class: 'pg-honest', role: 'note' }, ['\u2139\uFE0F ', p.honesty || 'Study companion \u2014 not an accredited degree.']),
        (p.outcomes || []).length ? h('div', null, [h('p', { class: 'rm-sub' }, 'You will be able to'), h('ul', { class: 'rm-out' }, p.outcomes.map(function (o) { return h('li', null, String(o)); }))]) : null,
        h('div', { class: 'rm-acts no-print' }, [startB, h('button', { type: 'button', class: 'btn ghost', onclick: function () { document.body.classList.add('pg-printing'); setTimeout(function () { window.print(); setTimeout(function () { document.body.classList.remove('pg-printing'); }, 400); }, 30); } }, '🖨\uFE0F Print / save as PDF'), h('a', { class: 'btn ghost', href: '#/programmes' }, '\u2190 All programmes')])]),
      cs.length ? h('div', { class: 'no-print', html: VV2.ring(pr.pct, 120, color, pr.pct + '% of this programme done') }) : null]));
    if (!cs.length) {
      w.appendChild(h('div', { class: 'card empty-state' }, [h('div', { class: 'es-art', 'aria-hidden': 'true' }, '🚧'), h('h2', null, 'This programme is being written'), h('p', null, 'Its courses will appear here automatically as soon as they are published' + (p.auto ? ' (packs named ' + p.auto + '\u2026)' : '') + '.'), h('a', { class: 'btn', href: '#/programmes' }, 'See the other programmes')]));
      return;
    }
    var grid = h('div', { class: 'pg-terms', role: 'list', 'aria-label': 'Terms' }); w.appendChild(grid);
    var nowMarked = false;
    terms.forEach(function (t, i) {
      var tm = minutes(t.courses), tl = 0, td = 0;
      t.courses.forEach(function (c) { tl += +c.lessons || 0; td += store.courseDone(c.id, +c.lessons || 0); });
      var tp = tl ? Math.round(td / tl * 100) : 0, now = !nowMarked && tp < 100; if (now) nowMarked = true;
      grid.appendChild(h('section', { class: 'card pg-term' + (tp >= 100 ? ' done' : '') + (now ? ' now' : ''), role: 'listitem', 'aria-label': t.title }, [
        h('div', { class: 'pg-term-h' }, [h('h3', null, t.title), h('small', null, t.courses.length + ' course' + (t.courses.length === 1 ? '' : 's') + ' \u00b7 ' + VV2.hrs(tm) + ' \u00b7 ' + tp + '%' + (now ? ' \u00b7 👉 you are here' : ''))]),
        h('div', { class: 'cc-bar', 'aria-hidden': 'true' }, h('i', { style: { width: tp + '%' } })),
        h('ul', { class: 'pg-chips' }, t.courses.map(function (c) {
          var n = +c.lessons || 0, d = store.courseDone(c.id, n), cp = n ? Math.round(d / n * 100) : 0;
          return h('li', null, h('a', { class: 'rm-chip pg-chip' + (cp >= 100 ? ' done' : cp > 0 ? ' prog' : ''), href: '#/course/' + encodeURIComponent(c.id), title: c.title + ' \u2014 ' + VV2.hrs(c.minutes) + (c.pending ? ' (new \u2014 joining the catalogue soon)' : '') }, [
            h('span', { 'aria-hidden': 'true' }, cp >= 100 ? '\u2705' : cp > 0 ? '\u25D0' : (c.icon || '\u25CB')), h('span', { class: 'pg-chip-t' }, c.title), h('small', null, (cp > 0 && cp < 100 ? cp + '% \u00b7 ' : '') + VV2.hrs(c.minutes)),
            h('span', { class: 'sr op-sr' }, cp >= 100 ? ' (done)' : cp > 0 ? ' (' + cp + '% done)' : ' (not started)')]));
        }))]));
    });
    var rms = (p.roadmaps || []);
    var rel = list.filter(function (x) { return x.id !== p.id && x.level === p.level && (x.group && x.group === p.group); }).slice(0, 8);
    if (rms.length || rel.length) {
      w.appendChild(h('section', { class: 'card pg-rel no-print' }, [
        rms.length ? h('div', null, [h('h2', null, '🗺\uFE0F Related career roadmaps'), h('div', { class: 'rm-chips' }, rms.map(function (r) { return h('a', { class: 'rm-chip', href: '#/roadmaps/' + encodeURIComponent(r) }, ['🧭 ', r.replace(/-/g, ' ').replace(/\b\w/g, function (x) { return x.toUpperCase(); })]); }))]) : null,
        rel.length ? h('div', null, [h('h2', null, 'Other ' + (p.group || L.name)), h('div', { class: 'rm-chips' }, rel.map(function (x) { return h('a', { class: 'rm-chip', href: '#/programmes/' + encodeURIComponent(x.id) }, (x.icon || '') + ' ' + x.short); }))]) : null]));
    }
  }
})();
